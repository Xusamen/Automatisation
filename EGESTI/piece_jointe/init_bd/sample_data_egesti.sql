INSERT INTO ERESTO.pa_calendrier
  (DATE_CAL,
   NUM_JOUR,
   NOM_JOUR,
   NUM_MOIS,
   NOM_MOIS,
   NUM_SEM,
   NOM_SEM,
   DAT_DEB_SEM,
   DAT_FIN_SEM,
   DAT_DEB_MOIS,
   DAT_FIN_MOIS,
   NUM_TRIM,
   NOM_TRIM,
   DAT_DEB_TRIM,
   DAT_FIN_TRIM)
SELECT
    DATE_ADD('2024-01-01', INTERVAL t.n DAY) DATE_CAL,
    dayofweek(DATE_ADD('2024-01-01', INTERVAL t.n DAY)) NUM_JOUR,
    CASE dayofweek(DATE_ADD('2024-01-01', INTERVAL t.n DAY))
    WHEN 2 THEN 'Lundi' WHEN 3 THEN 'Mardi' WHEN 4 THEN 'Mercredi'     WHEN 5 THEN 'Jeudi'     WHEN 6 THEN 'Vendredi'     WHEN 7 THEN 'Samedi'
    else 'Dimanche' end NOM_JOUR,
    month(DATE_ADD('2024-01-01', INTERVAL t.n DAY)) NUM_MOIS,
      CASE month(DATE_ADD('2024-01-01', INTERVAL t.n DAY))
    WHEN 1 THEN 'Janvier' WHEN 2 THEN 'Février' WHEN 3 THEN 'Mars'     WHEN 4 THEN 'Avril'     WHEN 5 THEN 'Mai'     WHEN 6 THEN 'Juin'
     WHEN 7 THEN 'Juillet'  WHEN 8 THEN 'Aout'  WHEN 9 THEN 'Septembre'  WHEN 10 THEN 'Octobre'  WHEN 11 THEN 'Novembre'     else 'Décembre' end  NOM_MOIS,
  weekofyear(DATE_ADD('2024-01-01', INTERVAL t.n DAY)) NUM_SEM,
 concat('Semaine ', cast(weekofyear(DATE_ADD('2024-01-01', INTERVAL t.n DAY)) as char(5)),' ',cast(year(DATE_ADD('2024-01-01', INTERVAL t.n DAY)) as char(4))) NOM_SEM,
 SUBDATE(DATE_ADD('2024-01-01', INTERVAL t.n DAY), WEEKDAY(DATE_ADD('2024-01-01', INTERVAL t.n DAY))) DAT_DEB_SEM,
DATE_ADD(DATE_ADD('2024-01-01', INTERVAL t.n DAY),INTERVAL 6-WEEKDAY(DATE_ADD('2024-01-01', INTERVAL t.n DAY)) DAY)  DAT_FIN_SEM,
DATE_SUB(DATE_ADD('2024-01-01', INTERVAL t.n DAY), INTERVAL DAYOFMONTH(DATE_ADD('2024-01-01', INTERVAL t.n DAY))-1 DAY) DAT_DEB_MOIS ,
 LAST_DAY((DATE_ADD('2024-01-01', INTERVAL t.n DAY))) DAT_FIN_MOIS ,
 quarter(DATE_ADD('2024-01-01', INTERVAL t.n DAY)) NUM_TRIM,
 CONCAT('Trimestre ',quarter(DATE_ADD('2024-01-01', INTERVAL t.n DAY))) NOM_TRIM,
 MAKEDATE(YEAR(DATE_ADD('2024-01-01', INTERVAL t.n DAY)), 1) + INTERVAL QUARTER(DATE_ADD('2024-01-01', INTERVAL t.n DAY)) QUARTER - INTERVAL    1 QUARTER DAT_DEB_TRIM,
 MAKEDATE(YEAR(DATE_ADD('2024-01-01', INTERVAL t.n DAY)), 1) + INTERVAL QUARTER(DATE_ADD('2024-01-01', INTERVAL t.n DAY)) QUARTER - INTERVAL 1 DAY DAT_FIN_TRIM
