SELECT
    DATE_ADD(concat(year(current_date()),'-10-01'), INTERVAL t.n DAY) DATE_SCOLAIRE,
    (select ID_AN_SCOLAIRE from pgetab.pa_annee_scolaire where FL_AN_ACTF='O')  ID_AN_SCOLAIRE,
    dayofweek(DATE_ADD(concat(year(current_date()),'-10-01'), INTERVAL t.n DAY)) NUM_JOUR,
    CASE dayofweek(DATE_ADD(concat(year(current_date()),'-10-01'), INTERVAL t.n DAY))
    WHEN 2 THEN 'Lundi' WHEN 3 THEN 'Mardi' WHEN 4 THEN 'Mercredi'     WHEN 5 THEN 'Jeudi'     WHEN 6 THEN 'Vendredi'     WHEN 7 THEN 'Samedi'
    else 'Dimanche' end NM_JOUR,
    month(DATE_ADD(concat(year(current_date()),'-10-01'), INTERVAL t.n DAY)) NUM_MOIS,
      CASE month(DATE_ADD(concat(year(current_date()),'-10-01'), INTERVAL t.n DAY))
    WHEN 1 THEN 'Janvier' WHEN 2 THEN 'Février' WHEN 3 THEN 'Mars'     WHEN 4 THEN 'Avril'     WHEN 5 THEN 'Mai'     WHEN 6 THEN 'Juin'
     WHEN 7 THEN 'Juillet'  WHEN 8 THEN 'Aout'  WHEN 9 THEN 'Septembre'  WHEN 10 THEN 'Octobre'  WHEN 11 THEN 'Novembre'     else 'Décembre' end  NM_MOIS,
     WEEK(DATE_ADD(concat(year(current_date()),'-10-01'), INTERVAL t.n DAY))+1 NUM_SEM,
     SUBDATE(DATE_ADD(concat(year(current_date()),'-10-01'), INTERVAL t.n DAY), WEEKDAY(DATE_ADD(concat(year(current_date()),'-10-01'), INTERVAL t.n DAY))) DATE_DEB_SEM,
