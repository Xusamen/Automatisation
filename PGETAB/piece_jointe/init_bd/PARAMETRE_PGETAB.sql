     LAST_DAY(DATE_ADD(concat(year(current_date()),'-10-01'), INTERVAL t.n DAY)) DATE_FIN_MOIS,
   case when
    DATE_ADD(concat(year(current_date()),'-10-01'), INTERVAL t.n DAY) in (
   concat(year(current_date()),'-10-31') ,concat(year(current_date()),'-11-01'),concat(year(current_date()),'-12-11') ,concat(year(current_date())+1,'-03-09')
